// Generate Zod schemas from the JSON Schema that Pydantic exports (single source of truth).
// usage: node scripts/gen-zod.mjs [--stdout]
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { jsonSchemaToZod } from "json-schema-to-zod";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../lib/schemas");
const TARGETS = [
  ["petition", "petitionSchema"],
  ["petition_mapping", "petitionMappingSchema"],
  ["prong_review", "prongReviewSchema"],
  ["letter_packet", "letterPacketSchema"],
  ["letter_review", "letterReviewSchema"],
  ["merits_review", "meritsReviewSchema"],
  ["merits_input", "meritsInputSchema"],
];

// Inline "#/$defs/X" references so the generated Zod is self-contained.
function deref(node, defs) {
  if (Array.isArray(node)) return node.map((n) => deref(n, defs));
  if (node && typeof node === "object") {
    if (typeof node.$ref === "string") {
      const name = node.$ref.replace("#/$defs/", "");
      if (!(name in defs)) throw new Error(`unresolved $ref ${node.$ref}`);
      return deref(defs[name], defs);
    }
    return Object.fromEntries(
      Object.entries(node).filter(([k]) => k !== "$defs").map(([k, v]) => [k, deref(v, defs)]),
    );
  }
  return node;
}

const outputs = TARGETS.map(([file, name]) => {
  const schema = JSON.parse(readFileSync(path.join(dir, `${file}.schema.json`), "utf8"));
  const code = jsonSchemaToZod(deref(schema, schema.$defs ?? {}), { name, module: "esm" });
  return `// GENERATED by web/scripts/gen-zod.mjs from ${file}.schema.json (Pydantic). Do not edit.\n${code}\n`;
});

if (process.argv.includes("--stdout")) {
  process.stdout.write(outputs.join("\n// ---\n"));
} else {
  TARGETS.forEach(([file], i) => writeFileSync(path.join(dir, `${file}.zod.ts`), outputs[i]));
}
